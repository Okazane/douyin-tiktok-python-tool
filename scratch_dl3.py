"""
Tự động chuyển cookie dạng raw string sang Netscape cookies.txt chuẩn
+ yt-dlp tải Douyin video.
"""
import sys, os, re, subprocess, shutil
from pathlib import Path
from http.cookiejar import MozillaCookieJar
from http.cookies import SimpleCookie
import time

COOKIE_RAW_FILE = Path("D:/Antigravity/TIKTOK/cookies.txt")
COOKIE_NETSCAPE = Path("D:/Antigravity/TIKTOK/cookies_netscape.txt")

def raw_to_netscape(raw_file: Path, netscape_file: Path):
    """Convert raw cookie string to Netscape format."""
    content = raw_file.read_text(encoding='utf-8').strip()
    
    # Skip if already Netscape
    if '\t' in content or content.startswith('# Netscape'):
        shutil.copy2(raw_file, netscape_file)
        return
    
    lines = ["# Netscape HTTP Cookie File", "# Generated by Douyin2TikTok", ""]
    
    for item in content.split(';'):
        item = item.strip()
        if '=' in item:
            name, val = item.split('=', 1)
            name = name.strip()
            val = val.strip()
            if not name:
                continue
            # Netscape format: domain  flag  path  secure  expiry  name  value
            lines.append(f".douyin.com\tTRUE\t/\tTRUE\t{int(time.time()) + 86400*30}\t{name}\t{val}")
    
    netscape_file.write_text('\n'.join(lines), encoding='utf-8')
    print(f"✅ Đã chuyển đổi {len(lines)-3} cookies sang Netscape format")

def download_with_netscape(video_url: str, output_path: Path):
    """Download using yt-dlp with Netscape cookies."""
    cmd = [
        'yt-dlp',
        '--cookiefile', str(COOKIE_NETSCAPE),
        '-f', 'best[ext=mp4]/best',
        '-o', str(output_path),
        '--no-warnings',
        video_url
    ]
    print(f"⬇️ Tải video: {video_url}")
    result = subprocess.run(cmd, capture_output=True, text=True, encoding='utf-8', errors='replace')
    print(result.stdout)
    if result.returncode != 0:
        print(f"❌ yt-dlp lỗi: {result.stderr}")
        return False
    return output_path.exists()

if __name__ == '__main__':
    video_url = "https://www.douyin.com/video/7683569041939647795"
    output = Path("D:/Antigravity/TIKTOK/temp/source.mp4")
    output.parent.mkdir(parents=True, exist_ok=True)
    
    if output.exists():
        output.unlink()
    
    # Step 1: Convert raw cookies to Netscape
    raw_to_netscape(COOKIE_RAW_FILE, COOKIE_NETSCAPE)
    
    # Step 2: Download
    success = download_with_netscape(video_url, output)
    
    if success:
        size_mb = output.stat().st_size / 1024 / 1024
        print(f"✅ Tải thành công! File: {output} ({size_mb:.1f} MB)")
    else:
        # Step 3: Try with --cookies-from-browser edge as fallback
        print("\n🔄 Thử fallback: rút cookie từ Edge browser...")
        cmd = [
            'yt-dlp',
            '--cookies-from-browser', 'edge',
            '-f', 'best[ext=mp4]/best',
            '-o', str(output),
            '--no-warnings',
            video_url
        ]
        result = subprocess.run(cmd, capture_output=True, text=True, encoding='utf-8', errors='replace')
        print(result.stdout)
        if output.exists():
            size_mb = output.stat().st_size / 1024 / 1024
            print(f"✅ Tải thành công qua Edge! File: {output} ({size_mb:.1f} MB)")
        else:
            print(f"❌ Cả hai phương pháp đều thất bại: {result.stderr}")
